-- =============================================================================
--  V2 — notifications and their delivery attempt history
-- =============================================================================

-- -----------------------------------------------------------------------------
--  notifications
-- -----------------------------------------------------------------------------
--  One row per delivery request. The row IS the record of the request; the
--  Kafka event is only a trigger to process it, which is why the consumer
--  re-reads this table rather than trusting the event payload.
-- -----------------------------------------------------------------------------
CREATE TABLE notifications (
    -- UUID rather than a sequence, for two reasons that both matter here:
    --
    --   1. A notification id is handed to external callers and appears in
    --      Kafka events. A sequential integer would leak throughput volume
    --      and invite someone to try the neighbouring id.
    --   2. The id is generated by the application BEFORE the insert, so the
    --      outbox event in the same transaction can reference it without a
    --      round trip to read back a generated key.
    --
    -- The application generates these time-ordered (UUIDv7-style): a fully
    -- random UUID as a primary key scatters inserts across the whole B-tree,
    -- which destroys index locality and page cache hit rates at volume.
    id                 UUID         PRIMARY KEY,

    channel            VARCHAR(16)  NOT NULL,
    status             VARCHAR(24)  NOT NULL DEFAULT 'PENDING',

    -- An opaque reference to the destination: an email address, an E.164
    -- phone number, or an internal user id for IN_APP.
    recipient          VARCHAR(320) NOT NULL,

    subject            VARCHAR(255) NULL,
    body               TEXT         NOT NULL,

    -- Free-form caller metadata (template name, locale, correlation data).
    -- jsonb rather than text so it can be queried and indexed later without a
    -- migration; also validates that what arrives is actually JSON.
    metadata           JSONB        NULL,

    -- Which account submitted it. Used to scope reads: a USER sees only their
    -- own notifications, an ADMIN sees everything.
    created_by         BIGINT       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,

    attempt_count      INTEGER      NOT NULL DEFAULT 0,
    max_attempts       INTEGER      NOT NULL DEFAULT 3,

    -- Sanitised. The provider's raw exception may contain the recipient, an
    -- API key fragment or a stack trace; the application truncates and strips
    -- before writing here, and this column is never returned to a non-admin.
    last_error         VARCHAR(500) NULL,

    -- Set when a retry is scheduled. The retry consumer uses it to decide
    -- whether a redelivered message is due yet.
    next_attempt_at    TIMESTAMPTZ  NULL,

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- First moved out of PENDING. Distinguishes "never picked up" from
    -- "picked up and still working", which is the first question asked when a
    -- notification appears stuck.
    processing_started_at TIMESTAMPTZ NULL,
    -- Reached a terminal state. completed_at - created_at is end-to-end latency.
    completed_at       TIMESTAMPTZ  NULL,

    -- Optimistic locking. Two consumers handling a duplicate Kafka event can
    -- both load the row; @Version makes the second write fail rather than
    -- silently overwrite the first one's outcome.
    version            BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT ck_notifications_channel CHECK (channel IN ('EMAIL', 'SMS', 'IN_APP')),

    -- The closed set of states. Enforced here as well as in the Java state
    -- machine so the invariant survives a direct psql session or a future
    -- service writing to this table.
    CONSTRAINT ck_notifications_status CHECK (status IN (
        'PENDING',           -- accepted, not yet picked up
        'PROCESSING',        -- claimed by a consumer, provider call in flight
        'RETRY_SCHEDULED',   -- transient failure, will be retried
        'SENT',              -- provider accepted it (terminal)
        'FAILED',            -- permanent failure, or retries exhausted (terminal)
        'DEAD_LETTERED'      -- could not even be processed; parked for inspection (terminal)
    )),

    CONSTRAINT ck_notifications_attempts  CHECK (attempt_count >= 0 AND attempt_count <= max_attempts + 1),
    CONSTRAINT ck_notifications_max       CHECK (max_attempts BETWEEN 1 AND 10),
    CONSTRAINT ck_notifications_recipient CHECK (length(btrim(recipient)) > 0),
    CONSTRAINT ck_notifications_body      CHECK (length(btrim(body)) > 0),

    -- A terminal state must have a completion timestamp, and a non-terminal
    -- one must not. Without this the "how long did it take" query silently
    -- returns nulls for rows that look finished.
    CONSTRAINT ck_notifications_completed_at CHECK (
        (status IN ('SENT', 'FAILED', 'DEAD_LETTERED') AND completed_at IS NOT NULL)
        OR
        (status IN ('PENDING', 'PROCESSING', 'RETRY_SCHEDULED') AND completed_at IS NULL)
    )
);

-- The listing endpoint: filter by caller, newest first. The id tiebreaker
-- makes the ordering total, so pagination cannot show or skip a row when two
-- notifications share a created_at.
CREATE INDEX idx_notifications_creator_created
    ON notifications (created_by, created_at DESC, id DESC);

-- Admin listing filtered by status, and the "what is stuck?" query.
CREATE INDEX idx_notifications_status_created
    ON notifications (status, created_at DESC);

CREATE INDEX idx_notifications_channel_created
    ON notifications (channel, created_at DESC);

-- Partial index for the sweeper that finds notifications whose retry is due.
-- Partial because the vast majority of rows are terminal and will never match;
-- indexing only the live ones keeps it small and hot.
CREATE INDEX idx_notifications_retry_due
    ON notifications (next_attempt_at)
    WHERE status = 'RETRY_SCHEDULED';

COMMENT ON TABLE  notifications                  IS 'Delivery requests. The row is authoritative; the Kafka event is only a trigger.';
COMMENT ON COLUMN notifications.id               IS 'Time-ordered UUID generated by the application before insert, so the outbox event can reference it in the same transaction.';
COMMENT ON COLUMN notifications.last_error       IS 'Sanitised and truncated. Never contains a stack trace or provider credentials.';
COMMENT ON COLUMN notifications.version          IS 'Optimistic lock. Makes a duplicate Kafka event fail loudly rather than overwrite an outcome.';
COMMENT ON COLUMN notifications.metadata         IS 'Caller-supplied JSON. jsonb so it is validated on write and queryable later.';


-- -----------------------------------------------------------------------------
--  notification_attempts
-- -----------------------------------------------------------------------------
--  Append-only history: one row per provider call. Separate from the
--  notifications table because "what is the current state" and "what happened
--  on attempt 2 of 3" are different questions, and the answer to the second
--  must not be overwritten by the third attempt.
--
--  This is what makes "why did this fail?" answerable after the fact.
-- -----------------------------------------------------------------------------
CREATE TABLE notification_attempts (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id UUID         NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,

    attempt_number  INTEGER      NOT NULL,
    outcome         VARCHAR(24)  NOT NULL,

    -- Whatever the provider called this delivery. Null when the provider never
    -- answered.
    provider_reference VARCHAR(100) NULL,

    -- Sanitised, same policy as notifications.last_error.
    error_message   VARCHAR(500) NULL,

    -- How long the provider call took. The p99 of this is the first thing to
    -- look at when the queue starts backing up.
    duration_ms     INTEGER      NULL,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_attempts_outcome CHECK (outcome IN (
        'SUCCESS',            -- the provider accepted it
        'TRANSIENT_FAILURE',  -- worth retrying: timeout, 5xx, rate limit
        'PERMANENT_FAILURE'   -- not worth retrying: malformed recipient, rejected content
    )),
    CONSTRAINT ck_attempts_number   CHECK (attempt_number >= 1),
    CONSTRAINT ck_attempts_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

-- One row per attempt number per notification. This is the guarantee that a
-- duplicate Kafka event cannot silently append a second "attempt 2": the
-- insert collides and the consumer discovers it is a replay.
CREATE UNIQUE INDEX uq_attempts_notification_number
    ON notification_attempts (notification_id, attempt_number);

CREATE INDEX idx_attempts_notification ON notification_attempts (notification_id, attempt_number);
CREATE INDEX idx_attempts_outcome      ON notification_attempts (outcome, created_at DESC);

COMMENT ON TABLE  notification_attempts        IS 'Append-only provider call history. One row per attempt; never updated.';
COMMENT ON INDEX  uq_attempts_notification_number IS 'Makes a duplicate attempt record impossible, so a replayed Kafka event is detected rather than double-counted.';
