-- =============================================================================
--  V1 — API consumers
-- =============================================================================
--  Accounts that may call this service. A notification platform is internal
--  infrastructure: its callers are other services and a handful of operators,
--  not the public. There is therefore no self-registration endpoint, and this
--  table stays small.
--
--  NO USER IS SEEDED HERE. Seeding one would put a credential in version
--  control. The development administrator is created at startup from
--  environment configuration, and only outside the 'prod' profile.
-- =============================================================================

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,

    -- BCrypt output is always 60 characters; 100 leaves room for a future
    -- migration to argon2 or a longer bcrypt variant without a schema change.
    password_hash VARCHAR(100) NOT NULL,

    role          VARCHAR(20)  NOT NULL DEFAULT 'ROLE_USER',
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,

    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,

    -- The role set is closed. A CHECK rather than an enum type: adding a value
    -- to a PostgreSQL enum is a schema change either way, and a CHECK is
    -- readable in \d output and portable.
    CONSTRAINT ck_users_role     CHECK (role IN ('ROLE_USER', 'ROLE_ADMIN')),
    CONSTRAINT ck_users_username CHECK (length(btrim(username)) >= 3)
);

-- Functional index: makes the lookup case-insensitive AND enforces that
-- 'Admin' and 'admin' cannot both exist. A plain unique index on username
-- would permit both and the login would be ambiguous.
CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username));

COMMENT ON TABLE  users               IS 'API consumers. Deliberately seeded empty — no credential in version control.';
COMMENT ON COLUMN users.password_hash IS 'BCrypt. The application never stores or logs the plain-text password.';
